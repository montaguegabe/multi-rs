#[test]
fn leaves_the_workspaces_own_skill_alone_and_first_repo_wins() {
    let (_tmp, ws) = workspace_dir(&["api", "web"], json!({}));
    add_skill(&ws, "api", "deploy");
    add_skill(&ws, "web", "deploy");
    add_skill(&ws, "api", "lint");
    add_skill(&ws, "web", "lint");
    write(&ws.join(".agents/skills/lint/SKILL.md"), "root's own\n");

    sync_all_skills(&paths(&ws)).unwrap();

    assert_eq!(
        link_target(&ws.join(".agents/skills/deploy")),
        "../../api/.agents/skills/deploy"
    );
    assert!(!ws.join(".agents/skills/lint").is_symlink());
    assert_eq!(
        read(&ws.join(".agents/skills/lint/SKILL.md")),
        "root's own\n"
    );
}

