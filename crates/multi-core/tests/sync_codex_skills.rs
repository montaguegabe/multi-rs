#[test]
fn doctor_warns_when_override_is_stale() {
    let (_tmp, ws) = workspace_dir(&["api"], json!({}));
    write(&ws.join("api/AGENTS.md"), "# API rules\n");
    sync_all_codex(&paths(&ws)).unwrap();
    assert!(!run_doctor_checks(&ws, &NO_REMOTES)
        .warnings
        .iter()
        .any(|w| w.contains(OVERRIDE_FILENAME)));

    write(&ws.join("AGENTS.md"), "# New root rules\n");

    assert!(run_doctor_checks(&ws, &NO_REMOTES)
        .warnings
        .iter()
        .any(|w| w.contains(OVERRIDE_FILENAME) && w.contains("out of date")));
}

#[test]
fn links_sub_repo_skills_relatively() {
    let (_tmp, ws) = workspace_dir(&["api"], json!({}));
    add_skill(&ws, "api", "deploy");
    std::fs::create_dir_all(ws.join("api/.agents/skills/notes")).unwrap();

    sync_all_skills(&paths(&ws)).unwrap();

    let link = ws.join(".agents/skills/deploy");
    assert_eq!(link_target(&link), "../../api/.agents/skills/deploy");
    assert!(link.join("SKILL.md").is_file());
    assert!(!ws.join(".agents/skills/notes").exists());
}

