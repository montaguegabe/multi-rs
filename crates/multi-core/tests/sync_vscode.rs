#[test]
fn nested_path_repo_prefixes_with_relative_path() {
    let ws = workspace();
    let nested = ws.root.join("services/api");
    std::fs::create_dir_all(nested.parent().unwrap()).unwrap();
    std::fs::rename(ws.repo(0), &nested).unwrap();
    ws.update_multi_json(|config| {
        config["repos"][0]["path"] = json!("services/api");
    });
    write(
        &nested.join(".vscode/launch.json"),
        &json!({"configurations": [{"name": "Api"}]}).to_string(),
    );
    merge_launch_json(&ws.paths()).unwrap();
    let merged = read_json(&ws.root.join(".vscode/launch.json"));
    assert_eq!(
        merged["configurations"][0]["cwd"],
        "${workspaceFolder}/services/api"
    );
}
