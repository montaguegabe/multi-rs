#[test]
fn merge_launch_files() {
    let ws = workspace();
    write(
        &ws.repo(0).join(".vscode/launch.json"),
        &json!({
            "version": "0.2.0",
            "configurations": [
                {"name": "Repo0 PyLaunch", "type": "python", "request": "launch", "program": "${workspaceFolder}/main.py", "required": true},
                {"name": "Repo0 Another", "type": "node", "request": "attach", "port": 9229},
            ],
            "compounds": [{"name": "Repo0 Compound", "configurations": ["Repo0 PyLaunch", "Repo0 Another"]}],
        })
        .to_string(),
    );
    write(
        &ws.repo(1).join(".vscode/launch.json"),
        &json!({
            "version": "0.2.0",
            "configurations": [
                {"name": "Repo1 NodeLaunch", "type": "node", "request": "launch", "program": "${workspaceFolder}/app.js", "required": true},
                {"name": "Repo1 JavaDebug", "type": "java", "request": "attach", "port": 8000, "required": false},
            ],
        })
        .to_string(),
    );

    merge_launch_json(&ws.paths()).unwrap();

    let merged = read_json(&ws.root.join(".vscode/launch.json"));
    let configs = merged["configurations"].as_array().unwrap();
    let by_name = |name: &str| configs.iter().find(|c| c["name"] == name).unwrap().clone();
    assert_eq!(by_name("Repo0 PyLaunch")["cwd"], "${workspaceFolder}/repo0");
    assert_eq!(
        by_name("Repo0 PyLaunch")["program"],
        "${workspaceFolder}/repo0/main.py"
    );
    assert_eq!(by_name("Repo0 Another")["cwd"], "${workspaceFolder}/repo0");
    assert_eq!(
        by_name("Repo1 NodeLaunch")["program"],
        "${workspaceFolder}/repo1/app.js"
    );
    assert_eq!(
        by_name("Repo1 JavaDebug")["cwd"],
        "${workspaceFolder}/repo1"
    );

    let compounds = merged["compounds"].as_array().unwrap();
    assert_eq!(compounds.len(), 2);
    let master = compounds.iter().find(|c| c["name"] == "Root").unwrap();
    assert_eq!(
        master["configurations"],
        json!(["Repo0 PyLaunch", "Repo1 NodeLaunch"])
    );
    assert_eq!(master["preLaunchTask"], "All Required Tasks - Root");
    assert!(compounds.iter().any(|c| c["name"] == "Repo0 Compound"));

    let text = read(&ws.root.join(".vscode/launch.json"));
    assert!(text.contains("// Imported from: "));
    assert!(text.contains("repo0/.vscode/launch.json"));
}

#[test]
fn launch_shared_and_required_from_multi_json() {
    let ws = workspace();
    write(
        &ws.repo(0).join(".vscode/launch.json"),
        &json!({"configurations": [{"name": "Server", "type": "node"}], "compounds": [{"name": "Dev", "configurations": ["Server"]}]}).to_string(),
    );
    write(
        &ws.root.join(".vscode/launch.shared.json"),
        &json!({"compounds": [{"name": "Full Stack", "configurations": ["Server"]}]}).to_string(),
    );
    ws.update_multi_json(|config| {
        config["repos"][0]["requiredCompounds"] = json!(["Dev"]);
    });
    merge_launch_json(&ws.paths()).unwrap();
    let merged = read_json(&ws.root.join(".vscode/launch.json"));
    let names: Vec<&str> = merged["compounds"]
        .as_array()
        .unwrap()
        .iter()
        .map(|c| c["name"].as_str().unwrap())
        .collect();
    assert_eq!(names, vec!["Dev", "Full Stack", "Root"]);
}

#[test]
fn merge_tasks_files() {
    let ws = workspace();
    write(
        &ws.repo(0).join(".vscode/tasks.json"),
        &json!({
            "version": "2.0.0",
            "tasks": [
                {"label": "Repo0 Build", "type": "shell", "command": "./build.sh", "problemMatcher": [], "required": true},
                {"label": "Repo0 Test", "type": "process", "command": "pytest"},
            ],
        })
        .to_string(),
    );
    write(
        &ws.repo(1).join(".vscode/tasks.json"),
        &json!({
            "version": "2.0.0",
            "tasks": [{"label": "Repo1 Clean", "type": "npm", "script": "clean", "options": {"cwd": "${workspaceFolder}/specific_subfolder"}}],
        })
        .to_string(),
    );
    ws.update_multi_json(|config| {
        config["repos"][1]["requiredTasks"] = json!(["Repo1 Clean"]);
    });

    merge_tasks_json(&ws.paths()).unwrap();

    let merged = read_json(&ws.root.join(".vscode/tasks.json"));
    assert_eq!(merged["version"], "2.0.0");
    let tasks = merged["tasks"].as_array().unwrap();
    assert_eq!(tasks.len(), 4);
    let cwd =
        |label: &str| tasks.iter().find(|t| t["label"] == label).unwrap()["options"]["cwd"].clone();
    assert_eq!(cwd("Repo0 Build"), "${workspaceFolder}/repo0");
    assert_eq!(cwd("Repo0 Test"), "${workspaceFolder}/repo0");
    assert_eq!(
        cwd("Repo1 Clean"),
        "${workspaceFolder}/repo1/specific_subfolder"
    );
    let master = tasks
        .iter()
        .find(|t| t["label"] == "All Required Tasks - Root")
        .unwrap();
    assert_eq!(master["dependsOn"], json!(["Repo0 Build", "Repo1 Clean"]));
    assert_eq!(master["dependsOrder"], "parallel");
}

