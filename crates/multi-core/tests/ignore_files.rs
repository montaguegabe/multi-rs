fn workspace_dir(config: serde_json::Value) -> (tempfile::TempDir, std::path::PathBuf) {
    setup();
    let tmp = tempfile::tempdir().unwrap();
    let workspace = tmp.path().join("workspace");
    write(
        &workspace.join("multi.json"),
        &serde_json::to_string_pretty(&config).unwrap(),
    );
    (tmp, workspace)
}

fn lines(items: &[&str]) -> Vec<String> {
    items.iter().map(|s| s.to_string()).collect()
}

#[test]
fn set_managed_lines_preserves_existing_content() {
    let tmp = tempfile::tempdir().unwrap();
    let path = tmp.path().join(".gitignore");
    write(&path, "# Existing\nkeep-me\n");
    IgnoreFile::new(path.clone(), REPO_DIRECTORIES_BLOCK)
        .set_managed_lines(&lines(&["repo-a/", "repo-a"]))
        .unwrap();
    let content = read(&path);
    assert!(content.contains("# Existing\nkeep-me\n"));
    assert!(content.contains(&REPO_DIRECTORIES_BLOCK.begin_marker()));
    assert!(content.contains("repo-a/"));
    assert!(content.contains(&REPO_DIRECTORIES_BLOCK.end_marker()));
}

#[test]
fn repo_and_search_blocks_use_managed_markers() {
    let (_tmp, workspace) = workspace_dir(json!({
        "repos": [{"url": "https://github.com/test/repo-a"}, {"url": "https://github.com/test/repo-b"}]
    }));
    let paths = Paths::discover(&workspace, None).unwrap();
    update_gitignore_with_repos(&paths).unwrap();
    update_ignore_with_repos(&paths).unwrap();

    let gitignore = read(&workspace.join(".gitignore"));
    assert!(gitignore.contains(&REPO_DIRECTORIES_BLOCK.begin_marker()));
    assert!(gitignore.contains("the leading slash anchors each entry to the workspace root"));
    let gitignore_lines: Vec<&str> = gitignore.lines().collect();
    assert!(gitignore_lines.contains(&"/repo-a/"));
    assert!(gitignore_lines.contains(&"/repo-b"));
    let ignore = read(&workspace.join(".ignore"));
    assert!(ignore.contains(&SEARCHABLE_REPOS_BLOCK.begin_marker()));
    assert!(ignore.contains("# Allow us to search inside these gitignored directories"));
    assert!(ignore.lines().any(|l| l == "!/repo-a/"));
    assert!(ignore.lines().any(|l| l == "!/repo-b"));
}

#[test]
fn generated_files_block_updates_root_and_subrepos() {
    let (_tmp, workspace) = workspace_dir(json!({
        "repos": [{"url": "https://github.com/test/repo-a"}, {"url": "https://github.com/test/repo-b"}]
    }));
    let repo_a = workspace.join("repo-a");
    let repo_b = workspace.join("repo-b");
    std::fs::create_dir_all(repo_a.join(".git")).unwrap();
    std::fs::create_dir_all(repo_b.join(".git")).unwrap();
    write(&repo_a.join(".vscode/settings.shared.json"), "{}");

    update_gitignore_with_generated_files(&Paths::discover(&workspace, None).unwrap()).unwrap();

    let root = read(&workspace.join(".gitignore"));
    assert!(root.contains(&GENERATED_FILES_BLOCK.begin_marker()));
    assert!(root.contains("# These files are generated by multi."));
    assert!(root.contains(".vscode/settings.json"));
    assert!(root.contains(".vscode/tasks.json"));
    assert!(!root.contains("CLAUDE.md"));
    let a = read(&repo_a.join(".gitignore"));
    assert!(a.contains(".vscode/settings.json"));
    assert!(!a.contains("CLAUDE.md"));
    assert!(!repo_b.join(".gitignore").exists());
}

#[test]
fn generated_files_block_includes_agent_outputs_when_enabled() {
    let (_tmp, workspace) = workspace_dir(json!({
        "agentInstructions": {"enabled": true},
        "repos": [
            {"url": "https://github.com/test/repo-a", "description": "Backend API"},
            {"url": "https://github.com/test/repo-b"}
        ]
    }));
    let repo_a = workspace.join("repo-a");
    let repo_b = workspace.join("repo-b");
    std::fs::create_dir_all(repo_a.join(".git")).unwrap();
    std::fs::create_dir_all(repo_b.join(".git")).unwrap();
    write(&repo_b.join("AGENTS.parts/base.md"), "Repo instructions\n");

    update_gitignore_with_generated_files(&Paths::discover(&workspace, None).unwrap()).unwrap();

    let root = read(&workspace.join(".gitignore"));
    assert!(root.contains("CLAUDE.md") && root.contains("AGENTS.md"));
    assert!(!repo_a.join(".gitignore").exists());
    let b = read(&repo_b.join(".gitignore"));
    assert!(b.contains("CLAUDE.md") && b.contains("AGENTS.md"));
}

#[test]
fn generated_files_respects_manage_gitignore_false_and_clears_blocks() {
    let (_tmp, workspace) = workspace_dir(json!({
        "repos": [{"url": "https://github.com/test/repo-a", "manageGitignore": false}]
    }));
    let repo_a = workspace.join("repo-a");
    std::fs::create_dir_all(repo_a.join(".git")).unwrap();
    write(
        &repo_a.join(".gitignore"),
        &format!(
            "keep-me\n\n{}\n# These files are generated by multi.\nCLAUDE.md\nAGENTS.md\n{}\n",
            GENERATED_FILES_BLOCK.begin_marker(),
            GENERATED_FILES_BLOCK.end_marker()
        ),
    );
    update_gitignore_with_generated_files(&Paths::discover(&workspace, None).unwrap()).unwrap();
    assert_eq!(read(&repo_a.join(".gitignore")), "keep-me\n");
}

#[test]
fn remove_entries_removes_only_managed_lines_including_legacy_forms() {
    let tmp = tempfile::tempdir().unwrap();
    let workspace = tmp.path().join("workspace");
    write(
        &workspace.join(".gitignore"),
        &format!(
            "keep/\n\n{}\n/repo-a/\n/repo-a\nrepo-a/\nrepo-a\n/repo-b/\n/repo-b\n{}\n",
            REPO_DIRECTORIES_BLOCK.begin_marker(),
            REPO_DIRECTORIES_BLOCK.end_marker()
        ),
    );
    write(
        &workspace.join(".ignore"),
        &format!(
            "!keep/\n\n{}\n!/repo-a/\n!/repo-a\n!repo-a/\n!repo-a\n!/repo-b/\n!/repo-b\n{}\n",
            SEARCHABLE_REPOS_BLOCK.begin_marker(),
            SEARCHABLE_REPOS_BLOCK.end_marker()
        ),
    );
    let paths = Paths::at_root(&workspace, None);
    remove_gitignore_entries_for_repos(&paths, &["repo-a".to_string()]).unwrap();
    remove_ignore_entries_for_repos(&paths, &["repo-a".to_string()]).unwrap();
    let gitignore = read(&workspace.join(".gitignore"));
    assert!(gitignore.contains("keep/"));
    assert!(!gitignore.contains("repo-a"));
    assert!(gitignore.contains("/repo-b/"));
    let ignore = read(&workspace.join(".ignore"));
    assert!(ignore.contains("!keep/"));
    assert!(!ignore.contains("repo-a"));
    assert!(ignore.contains("!/repo-b/"));
}

#[test]
fn nested_paths_are_anchored_exactly() {
    let (_tmp, workspace) = workspace_dir(json!({
        "repos": [{"url": "https://github.com/test/api", "path": "services/api"}, {"url": "https://github.com/test/web"}]
    }));
    let paths = Paths::discover(&workspace, None).unwrap();
    update_gitignore_with_repos(&paths).unwrap();
    update_ignore_with_repos(&paths).unwrap();
    let lines: Vec<String> = read(&workspace.join(".gitignore"))
        .lines()
        .map(String::from)
        .collect();
    assert!(lines.contains(&"/services/api/".to_string()));
    assert!(!lines.contains(&"/api/".to_string()));
    assert!(lines.contains(&"/web/".to_string()));
    remove_gitignore_entries_for_repos(&paths, &["services/api".to_string()]).unwrap();
    let lines: Vec<String> = read(&workspace.join(".gitignore"))
        .lines()
        .map(String::from)
        .collect();
    assert!(!lines.contains(&"/services/api/".to_string()));
    assert!(lines.contains(&"/web/".to_string()));
}

