//! Multi-managed entries in `.gitignore` and `.ignore` files.

use std::collections::HashSet;
use std::path::{Path, PathBuf};

use crate::error::Result;
use crate::fsx;
use crate::managed_blocks::{
    get_managed_block_lines, has_managed_block, replace_managed_block, ManagedBlock,
};
use crate::paths::Paths;
use crate::repos::load_repos;
use crate::sync::agents::would_generate_agents_for_repo;
use crate::sync::codex::{would_generate_codex_override, OVERRIDE_IGNORE_ENTRY};
use crate::sync::skills::root_skill_link_entries;

pub const REPO_DIRECTORIES_BLOCK: ManagedBlock = ManagedBlock::new("repo-directories");
pub const SEARCHABLE_REPOS_BLOCK: ManagedBlock =
    ManagedBlock::new("search-inside-gitignored-repos");
pub const GENERATED_FILES_BLOCK: ManagedBlock = ManagedBlock::new("generated-files");

const REPO_DIRECTORIES_COMMENT: &str = "# multi avoids git submodules; the leading slash anchors each entry to the workspace root so it never matches a nested directory of the same name (e.g. .agents/skills). The trailing-slash form matches the repo directory; the bare form matches a root symlink/alias.";
const SEARCH_COMMENT: &str = "# Allow us to search inside these gitignored directories";
const GENERATED_FILES_COMMENT: &str = "# These files are generated by multi.";

/// One ignore-style file plus the managed block multi owns inside it.
pub struct IgnoreFile {
    pub path: PathBuf,
    pub block: ManagedBlock,
}

impl IgnoreFile {
    pub fn new(path: PathBuf, block: ManagedBlock) -> Self {
        IgnoreFile { path, block }
    }

    pub fn existing_lines(&self) -> Result<Vec<String>> {
        Ok(fsx::read_optional(&self.path)?
            .map(|text| text.lines().map(str::to_string).collect())
            .unwrap_or_default())
    }

    pub fn set_managed_lines(&self, lines: &[String]) -> Result<()> {
        replace_managed_block(&self.path, &self.block, lines)
    }

    /// Drop `lines` from the managed block, or from the whole file when the
    /// file predates managed blocks.
    pub fn remove_managed_lines(&self, lines: &[String]) -> Result<()> {
        let Some(existing_text) = fsx::read_optional(&self.path)? else {
            return Ok(());
        };
        let to_remove: HashSet<&str> = lines.iter().map(String::as_str).collect();
        if has_managed_block(&existing_text, &self.block)? {
            let next: Vec<String> = get_managed_block_lines(&existing_text, &self.block)?
                .into_iter()
                .filter(|line| !to_remove.contains(line.as_str()))
                .collect();
            return replace_managed_block(&self.path, &self.block, &next);
        }
        let updated: Vec<&str> = existing_text
            .lines()
            .filter(|line| !to_remove.contains(line))
            .collect();
        if updated.is_empty() {
            fsx::remove_file(&self.path)
        } else {
            fsx::write(
                &self.path,
                format!("{}\n", updated.join("\n").trim_end_matches('\n')),
            )
        }
    }
}

fn repo_entries(paths: &Paths) -> Result<Vec<String>> {
    let mut entries = vec![REPO_DIRECTORIES_COMMENT.to_string()];
    for repo in load_repos(paths)? {
        entries.push(format!("/{}/", repo.relative_path));
        entries.push(format!("/{}", repo.relative_path));
    }
    Ok(entries)
}

fn search_entries(paths: &Paths) -> Result<Vec<String>> {
    let mut entries = vec![SEARCH_COMMENT.to_string()];
    for repo in load_repos(paths)? {
        entries.push(format!("!/{}/", repo.relative_path));
        entries.push(format!("!/{}", repo.relative_path));
    }
    Ok(entries)
}

fn with_generated_files_header(entries: Vec<String>) -> Vec<String> {
    if entries.is_empty() {
        return entries;
    }
    let mut result = vec![GENERATED_FILES_COMMENT.to_string()];
    result.extend(entries);
    result
}

fn subrepo_generated_entries(repo_path: &Path, paths: &Paths) -> Result<Vec<String>> {
    let mut entries = Vec::new();
    if would_generate_agents_for_repo(repo_path, paths, false)? {
        entries.push("CLAUDE.md".to_string());
        entries.push("AGENTS.md".to_string());
    }
    let vscode_dir = repo_path.join(".vscode");
    if vscode_dir.join("settings.shared.json").exists()
        || vscode_dir.join("settings.local.json").exists()
    {
        entries.push(".vscode/settings.json".to_string());
    }
    Ok(with_generated_files_header(entries))
}

pub fn clear_subrepo_generated_file_block(repo_path: &Path) -> Result<()> {
    IgnoreFile::new(repo_path.join(".gitignore"), GENERATED_FILES_BLOCK).set_managed_lines(&[])
}

pub fn update_gitignore_with_repos(paths: &Paths) -> Result<()> {
    let gitignore = IgnoreFile::new(paths.gitignore_path(), REPO_DIRECTORIES_BLOCK);
    if paths.settings()?.is_monorepo() {
        return gitignore.set_managed_lines(&[]);
    }
    gitignore.set_managed_lines(&repo_entries(paths)?)
}

pub fn update_ignore_with_repos(paths: &Paths) -> Result<()> {
    let ignore = IgnoreFile::new(paths.vscode_ignore_path(), SEARCHABLE_REPOS_BLOCK);
    if paths.settings()?.is_monorepo() {
        return ignore.set_managed_lines(&[]);
    }
    ignore.set_managed_lines(&search_entries(paths)?)
}

fn removal_entries(repo_names: &[String], prefix: &str) -> Vec<String> {
    let mut entries = Vec::new();
    for name in repo_names {
        // Remove both the anchored form and the legacy unanchored form so
        // workspaces written by older multi versions migrate cleanly.
        entries.push(format!("{prefix}/{name}/"));
        entries.push(format!("{prefix}/{name}"));
        entries.push(format!("{prefix}{name}/"));
        entries.push(format!("{prefix}{name}"));
    }
    entries
}

pub fn remove_gitignore_entries_for_repos(paths: &Paths, repo_names: &[String]) -> Result<()> {
    if repo_names.is_empty() {
        return Ok(());
    }
    IgnoreFile::new(paths.gitignore_path(), REPO_DIRECTORIES_BLOCK)
        .remove_managed_lines(&removal_entries(repo_names, ""))
}

pub fn remove_ignore_entries_for_repos(paths: &Paths, repo_names: &[String]) -> Result<()> {
    if repo_names.is_empty() {
        return Ok(());
    }
    IgnoreFile::new(paths.vscode_ignore_path(), SEARCHABLE_REPOS_BLOCK)
        .remove_managed_lines(&removal_entries(repo_names, "!"))
}

/// Maintain the `generated-files` block in the root and every cloned sub-repo.
pub fn update_gitignore_with_generated_files(paths: &Paths) -> Result<()> {
    let mut root_entries: Vec<String> = [
        ".vscode/settings.json",
        ".vscode/tasks.json",
        ".vscode/launch.json",
        ".vscode/extensions.json",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect();
    if would_generate_agents_for_repo(&paths.root_dir, paths, true)? {
        root_entries.push("CLAUDE.md".to_string());
        root_entries.push("AGENTS.md".to_string());
    }
    if would_generate_codex_override(paths)? {
        root_entries.push(OVERRIDE_IGNORE_ENTRY.to_string());
    }
    root_entries.extend(root_skill_link_entries(paths)?);
    IgnoreFile::new(paths.gitignore_path(), GENERATED_FILES_BLOCK)
        .set_managed_lines(&with_generated_files_header(root_entries))?;

    let settings = paths.settings()?;
    if settings.is_monorepo() || !settings.has_repos() {
        return Ok(());
    }
    for repo in load_repos(paths)? {
        if !repo.path.join(".git").exists() {
            continue;
        }
        if !repo.manage_gitignore {
            clear_subrepo_generated_file_block(&repo.path)?;
            continue;
        }
        IgnoreFile::new(repo.path.join(".gitignore"), GENERATED_FILES_BLOCK)
            .set_managed_lines(&subrepo_generated_entries(&repo.path, paths)?)?;
    }
    Ok(())
}
