/// Merge settings, launch, tasks and extensions, then sync `.devcontainer`.
pub fn merge_vscode_configs(paths: &Paths) -> Result<()> {
    log::info!("Merging .vscode configuration files from all repositories...");
    merge_settings_json(paths)?;
    merge_launch_json(paths)?;
    merge_tasks_json(paths)?;
    merge_extensions_json(paths)?;
    sync_devcontainer(paths)?;
    log::info!("Done merging .vscode configuration files!");
    Ok(())
}

/// Python's `str.title()`: capitalize the first letter of every run of
/// letters, lowercase the rest. Used for the master compound/task names.
pub fn title_case(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut previous_is_letter = false;
    for c in text.chars() {
        if c.is_alphabetic() {
            if previous_is_letter {
                out.extend(c.to_lowercase());
            } else {
                out.extend(c.to_uppercase());
            }
            previous_is_letter = true;
        } else {
            out.push(c);
            previous_is_letter = false;
        }
    }
    out
}

