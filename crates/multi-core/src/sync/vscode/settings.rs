//! Merge `settings.json` files.

use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

use crate::error::Result;
use crate::ignore_files::update_gitignore_with_generated_files;
use crate::jsonc::{soft_read_json_file, write_jsonc_file};
use crate::paths::{vscode_config_dir, Paths};
use crate::repos::{load_repos, Repository};

use super::helpers::{deep_merge, VscodeFileMerger};

pub const LOCAL_GENERATED_SETTINGS_HEADER: &str = "This file is generated by multi from settings.shared.json and/or settings.local.json. Do not edit directly.";

fn load_repo_companion_settings(repo_path: &Path) -> (bool, Map<String, Value>) {
    let vscode_dir = vscode_config_dir(repo_path);
    let shared = vscode_dir.join("settings.shared.json");
    let local = vscode_dir.join("settings.local.json");
    let has_companion = shared.exists() || local.exists();
    let mut merged = Map::new();
    if shared.exists() {
        merged = deep_merge(&merged, &soft_read_json_file(&shared), None, None);
    }
    if local.exists() {
        merged = deep_merge(&merged, &soft_read_json_file(&local), None, None);
    }
    (has_companion, merged)
}

struct SettingsFileMerger<'a> {
    paths: &'a Paths,
}

impl VscodeFileMerger for SettingsFileMerger<'_> {
    fn paths(&self) -> &Paths {
        self.paths
    }

    fn destination_json_path(&self) -> PathBuf {
        self.paths.vscode_settings_path()
    }

    fn source_json_path(&self, repo_path: &Path) -> PathBuf {
        vscode_config_dir(repo_path).join("settings.json")
    }

    fn skip_keys(&self, _repo: &Repository) -> Option<Vec<String>> {
        self.paths.settings().ok().map(|s| s.vscode_skip_settings())
    }

    /// Regenerate the repo's settings.json from companion settings files when
    /// present: `settings.shared.json` / `settings.local.json` become the
    /// complete source of truth for the generated settings.json. Also applies
    /// `vscode.settingsOverrides` from the repo's multi.json entry.
    fn prepare_repo_json(
        &self,
        mut repo_json: Map<String, Value>,
        repo: &Repository,
    ) -> Result<Map<String, Value>> {
        let repo_settings_path = vscode_config_dir(&repo.path).join("settings.json");
        let raw = std::fs::read_to_string(&repo_settings_path).unwrap_or_default();
        let (has_companion, companion) = load_repo_companion_settings(&repo.path);

        if has_companion {
            repo_json = companion;
            write_jsonc_file(
                &repo_settings_path,
                &Value::Object(repo_json.clone()),
                Some(LOCAL_GENERATED_SETTINGS_HEADER),
            )?;
        } else if raw.starts_with(&format!("// {LOCAL_GENERATED_SETTINGS_HEADER}")) {
            write_jsonc_file(&repo_settings_path, &Value::Object(repo_json.clone()), None)?;
        }

        if let Some(overrides) = repo
            .vscode
            .as_ref()
            .and_then(|v| v.get("settingsOverrides"))
            .and_then(Value::as_object)
        {
            if !overrides.is_empty() {
                log::debug!("Applying settingsOverrides for {}", repo.name);
                repo_json = deep_merge(&repo_json, overrides, None, None);
            }
        }
        Ok(repo_json)
    }

    fn post_process_json(&self, mut merged: Map<String, Value>) -> Result<Map<String, Value>> {
        for (path, label) in [
            (self.paths.vscode_settings_shared_path(), "Shared"),
            (self.paths.vscode_settings_local_path(), "Local"),
        ] {
            if path.exists() {
                merged = deep_merge(&merged, &soft_read_json_file(&path), None, None);
            } else {
                log::debug!(
                    "{label} settings file not found at {}, skipping.",
                    crate::fsx::file_name(&path)
                );
            }
        }

        // Add Python paths for autocomplete.
        let python_paths: Vec<String> = load_repos(self.paths)?
            .into_iter()
            .filter(Repository::is_python)
            .map(|repo| repo.relative_path)
            .collect();
        if !python_paths.is_empty() {
            log::info!("Adding Python paths for autocomplete");
            let entry = merged
                .entry("python.autoComplete.extraPaths".to_string())
                .or_insert_with(|| Value::Array(Vec::new()));
            if let Value::Array(items) = entry {
                for path in python_paths {
                    let value = Value::String(path);
                    if !items.contains(&value) {
                        items.push(value);
                    }
                }
            }
        }
        Ok(merged)
    }
}

pub fn merge_settings_json(paths: &Paths) -> Result<()> {
    SettingsFileMerger { paths }.merge()?;
    update_gitignore_with_generated_files(paths)
}
