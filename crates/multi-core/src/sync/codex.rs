//! Give Codex the sub-repo instructions it cannot discover on its own.
//!
//! Codex assembles its instructions once per request from the project root
//! (the nearest `.git`) down to the working directory, taking at most one file
//! per directory: `AGENTS.override.md` if present, else `AGENTS.md`. It never
//! looks below the working directory, so a session started at the workspace
//! root never sees a sub-repo's `AGENTS.md`.
//!
//! `multi sync` therefore writes a root `AGENTS.override.md` that embeds the
//! root `AGENTS.md` verbatim followed by one section per sub-repo instruction
//! file. Codex reads the override instead of `AGENTS.md` and gets everything.
//! Claude Code never reads `AGENTS.override.md` and already loads nested
//! instruction files on demand, so it is unaffected.
//!
//! The root `AGENTS.md` is never modified. An `AGENTS.override.md` that multi
//! did not generate (no marker on its first line) is never replaced either; a
//! warning explains that the sub-repo instructions cannot be exposed until it
//! is moved aside. Re-check both tools' discovery rules when touching this: if
//! Codex starts reading nested `AGENTS.md` files, this module is redundant.

use std::path::{Path, PathBuf};

use crate::error::Result;
use crate::fsx;
use crate::paths::Paths;
use crate::repos::load_repos;
use crate::sync::agents::would_generate_agents_for_repo;

pub const OVERRIDE_FILENAME: &str = "AGENTS.override.md";
pub const GENERATED_MARKER: &str = "<!-- multi-generated: codex-override -->";
const GENERATED_NOTICE: &str = "<!-- Generated by `multi sync`. Codex reads only one instruction file per directory and never looks into sub-repos, so this file repeats AGENTS.md and appends each sub-repo's own instructions. Edit those files, not this one; `multi sync` regenerates it. -->";
const INSTRUCTION_FILENAMES: &[&str] = &["AGENTS.md", "CLAUDE.md"];
/// Codex's default `project_doc_max_bytes`; it truncates anything past this.
pub const CODEX_DOC_BYTE_LIMIT: usize = 32 * 1024;
const SETTINGS_KEY: &str = "codexOverride";

/// Enabled unless `multi.json` has `"codexOverride": {"enabled": false}`.
pub fn is_codex_override_enabled(paths: &Paths) -> Result<bool> {
    Ok(paths.settings()?.section_enabled(SETTINGS_KEY, true))
}

pub fn override_path(paths: &Paths) -> PathBuf {
    paths.root_dir.join(OVERRIDE_FILENAME)
}

/// Whether `path` is an override multi wrote (and may rewrite).
pub fn is_generated_override(path: &Path) -> bool {
    std::fs::read_to_string(path)
        .map(|text| text.lines().next().map(str::trim) == Some(GENERATED_MARKER))
        .unwrap_or(false)
}

fn instruction_file(directory: &Path) -> Option<PathBuf> {
    INSTRUCTION_FILENAMES
        .iter()
        .map(|name| directory.join(name))
        .find(|candidate| candidate.is_file())
}

fn sub_repo_sections(paths: &Paths) -> Result<Vec<(String, PathBuf)>> {
    let mut sections = Vec::new();
    for repo in load_repos(paths)? {
        if let Some(source) = instruction_file(&repo.path) {
            let label = repo.relative_path.trim_end_matches('/').to_string();
            sections.push((label, source));
        }
    }
    Ok(sections)
}

/// The override's content, or `None` when no sub-repo has instructions.
pub fn build_codex_override(paths: &Paths) -> Result<Option<String>> {
    let sections = sub_repo_sections(paths)?;
    if sections.is_empty() {
        return Ok(None);
    }
    let mut lines: Vec<String> = vec![
        GENERATED_MARKER.to_string(),
        GENERATED_NOTICE.to_string(),
        String::new(),
    ];
    if let Some(root_file) = instruction_file(&paths.root_dir) {
        lines.push(fsx::read_to_string(&root_file)?.trim_end().to_string());
        lines.push(String::new());
    }
    for (label, source) in sections {
        lines.push(format!("## Instructions for `{label}/`"));
        lines.push(String::new());
        lines.push(format!(
            "The following applies when working on files under `{label}/`. It is that repository's own `{}`.",
            fsx::file_name(&source)
        ));
        lines.push(String::new());
        lines.push(fsx::read_to_string(&source)?.trim_end().to_string());
        lines.push(String::new());
    }
    Ok(Some(format!("{}\n", lines.join("\n").trim_end())))
}

/// Whether `sync_all_codex` will own the root override after this sync.
///
/// Counts sub-repos whose instruction file does not exist yet but will be
/// generated from `AGENTS.parts` later in the same sync.
pub fn would_generate_codex_override(paths: &Paths) -> Result<bool> {
    if !is_codex_override_enabled(paths)? {
        return Ok(false);
    }
    let target = override_path(paths);
    if target.exists() && !is_generated_override(&target) {
        return Ok(false);
    }
    if !sub_repo_sections(paths)?.is_empty() {
        return Ok(true);
    }
    for repo in load_repos(paths)? {
        if repo.path.exists() && would_generate_agents_for_repo(&repo.path, paths, false)? {
            return Ok(true);
        }
    }
    Ok(false)
}

/// Write the root `AGENTS.override.md` for Codex, never over user content.
pub fn sync_all_codex(paths: &Paths) -> Result<()> {
    if !is_codex_override_enabled(paths)? {
        log::debug!("Codex override generation is disabled");
        return Ok(());
    }
    let target = override_path(paths);
    let Some(content) = build_codex_override(paths)? else {
        if is_generated_override(&target) {
            fsx::remove_file(&target)?;
            log::info!("🗑️ Removed {OVERRIDE_FILENAME}: no sub-repo has instructions");
        }
        return Ok(());
    };

    if target.exists() && !is_generated_override(&target) {
        log::warn!(
            "⚠️  Cannot write {OVERRIDE_FILENAME}: the workspace has one that multi did not generate, so Codex will not see the sub-repo AGENTS.md instructions. Move its contents into AGENTS.md (or delete it) and rerun `multi sync`."
        );
        return Ok(());
    }

    let size = content.len();
    if size > CODEX_DOC_BYTE_LIMIT {
        log::warn!(
            "⚠️  {OVERRIDE_FILENAME} is {size} bytes; Codex truncates instructions past project_doc_max_bytes (default {CODEX_DOC_BYTE_LIMIT}). Shorten the instruction files or raise the limit in Codex config."
        );
    }

    if target.is_file() && fsx::read_to_string(&target)? == content {
        log::debug!("{OVERRIDE_FILENAME} is up to date");
        return Ok(());
    }
    fsx::write(&target, content)?;
    log::info!("✅ Generated {OVERRIDE_FILENAME} for Codex");
    Ok(())
}

/// A doctor warning when the override is missing, stale or not ours.
pub fn codex_override_problem(paths: &Paths) -> Result<Option<String>> {
    if !is_codex_override_enabled(paths)? {
        return Ok(None);
    }
    let target = override_path(paths);
    let expected = build_codex_override(paths)?;
    if target.exists() && !is_generated_override(&target) {
        return Ok(expected.map(|_| {
            format!(
                "{OVERRIDE_FILENAME} was not generated by multi, so Codex does not see the sub-repo AGENTS.md instructions. Move its contents into AGENTS.md and run `multi sync`."
            )
        }));
    }
    let Some(expected) = expected else {
        return Ok(target
            .exists()
            .then(|| format!("{OVERRIDE_FILENAME} is stale; run `multi sync` to remove it.")));
    };
    let current = if target.is_file() {
        Some(fsx::read_to_string(&target)?)
    } else {
        None
    };
    if current.as_deref() != Some(expected.as_str()) {
        return Ok(Some(format!(
            "{OVERRIDE_FILENAME} is missing or out of date with AGENTS.md and the sub-repo instruction files; run `multi sync`."
        )));
    }
    Ok(None)
}
